/**
    The typeface, drawn.

    One entry per glyph: a Unicode code point and eight rows of eight cells,
    written the way you read them -- **top row first**. `#` is ink, `.` is
    paper. Font.cpp flips them to OpenGL's bottom-up order exactly once, at
    parse time, and nothing after that knows this file was written the other way
    up.

    Letters, digits and punctuation are drawn on a 5x7 body: columns 1..5 and
    the top seven rows, with descenders in row 8. Column 0 and columns 6..7 are
    the side bearing, which is why the characters have air around them when the
    grid is coarse. Block and box-drawing glyphs use the whole cell, because
    there is no such thing as a block with a side bearing.

    Two things follow from the fact that this is the only description of the
    font anywhere:

    - **Editing a glyph moves it in the ramp.** Nothing hard-codes an ordering,
      so a redrawn `@` is re-measured and lands wherever its ink puts it. See
      Font.h.
    - **The order of this array is the atlas layout.** A glyph's index is its
      slot for the life of the process, so inserting one in the middle is free
      but the array must not exceed kAtlasCols * kAtlasRows entries.

    Drawn by hand for this project, so the whole font is under the repository's
    MIT licence with nothing vendored and nothing to attribute.

    `asctest --atlas /tmp/atlas.png` renders the lot. That is the only sensible
    way to check a change here -- a wrong bit in a glyph is invisible in the
    source and obvious in the picture.
*/

